"""Seedance 2.5 reference-to-video (720p) proxy with real Auto duration.

Uses supported Cog list[Path] inputs instead of unsupported Optional[Path].
The actual video is generated by fal.ai; Replicate hosts only this adapter.
"""

from tempfile import NamedTemporaryFile

import requests
from cog import BasePredictor, Input, Path, Secret

FAL_ENDPOINT = "bytedance/seedance-2.5/us/reference-to-video"


def build_arguments(prompt, duration, aspect_ratio, generate_audio, image_urls, video_urls):
    if not prompt.strip():
        raise ValueError("Prompt cannot be empty")
    if duration not in ("Auto", "30"):
        raise ValueError("Duration must be Auto or 30")
    if not image_urls and not video_urls:
        raise ValueError("Add at least one image or video reference")

    args = {
        "prompt": prompt,
        "task": "reference",
        "resolution": "720p",
        "duration": "auto" if duration == "Auto" else "30",
        "aspect_ratio": aspect_ratio,
        "generate_audio": generate_audio,
    }
    if image_urls:
        args["image_urls"] = image_urls
    if video_urls:
        args["video_urls"] = video_urls
    return args


class Predictor(BasePredictor):
    def predict(
        self,
        prompt: str = Input(description="Video prompt; use @Image1, @Image2, @Video1, etc."),
        fal_api_key: Secret = Input(description="fal.ai API key (secret). Do not put it in the prompt."),
        duration: str = Input(
            description="Auto = model chooses 4-30 seconds; 30 = exactly 30 seconds",
            default="Auto",
            choices=["Auto", "30"],
        ),
        aspect_ratio: str = Input(
            description="Video aspect ratio",
            default="16:9",
            choices=["16:9", "9:16", "21:9", "4:3", "3:4", "1:1", "auto"],
        ),
        generate_audio: bool = Input(description="Generate ambient/SFX audio", default=True),
        images: list[Path] = Input(
            description="Reference images (multiple files in order @Image1, @Image2, etc.)",
            default=[],
        ),
        videos: list[Path] = Input(
            description="Optional reference videos (multiple files in order @Video1, etc.)",
            default=[],
        ),
    ) -> Path:
        import fal_client

        key = fal_api_key.get_secret_value().strip()
        if not key:
            raise ValueError("fal.ai API key is required")
        fal = fal_client.SyncClient(key=key)
        image_urls = [fal.upload_file(str(item)) for item in images]
        video_urls = [fal.upload_file(str(item)) for item in videos]
        args = build_arguments(prompt, duration, aspect_ratio, generate_audio, image_urls, video_urls)
        result = fal.subscribe(FAL_ENDPOINT, arguments=args)
        url = result.get("video", {}).get("url")
        if not isinstance(url, str) or not url.startswith("https://"):
            raise RuntimeError("fal.ai did not return an HTTPS video URL")

        with NamedTemporaryFile(suffix=".mp4", delete=False) as target:
            with requests.get(url, stream=True, timeout=(20, 180)) as response:
                response.raise_for_status()
                for chunk in response.iter_content(chunk_size=2 * 1024 * 1024):
                    if chunk:
                        target.write(chunk)
            return Path(target.name)
